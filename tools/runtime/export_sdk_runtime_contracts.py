"""Generate SDK validation data from the admitted Runtime schema, never RFC files."""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from runtime.client_contracts import ClientContracts

TARGET = ROOT / "sdk/client-runtime-schema.ts"
KEYWORDS = {"$ref", "type", "properties", "required", "additionalProperties", "items", "minItems", "maxItems",
            "uniqueItems", "minLength", "maxLength", "minimum", "maximum", "pattern", "format", "const", "enum",
            "allOf", "anyOf", "oneOf", "if", "then", "else", "title", "description", "default", "minProperties"}


def generate():
    contracts = ClientContracts()
    definitions = contracts.schema(contracts.model_names[0])["$defs"]

    def check(schema):
        if type(schema) is bool:
            return
        if type(schema) is not dict or set(schema) - KEYWORDS:
            raise ValueError("SDK schema dialect requires an explicit validator evolution")
        if "$ref" in schema and (not schema["$ref"].startswith("#/$defs/") or schema["$ref"][8:] not in definitions):
            raise ValueError("SDK contracts permit only packaged local references")
        if "format" in schema and schema["format"] != "date-time":
            raise ValueError("SDK schema format needs an explicit checker")
        for child in schema.get("properties", {}).values():
            check(child)
        for name in ("items", "additionalProperties", "if", "then", "else"):
            if name in schema:
                check(schema[name])
        for name in ("allOf", "anyOf", "oneOf"):
            for child in schema.get(name, []):
                check(child)
    for schema in definitions.values():
        check(schema)
    encoded = json.dumps(definitions, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    lines = ["// Generated by tools/runtime/export_sdk_runtime_contracts.py. Do not edit.",
             "// Validation is not authorization or Native evidence. Source: admitted Runtime schema.",
             'import type * as DTO from "./client-contracts.ts";',
             'import type { JsonSchema } from "./client-validation.ts";',
             'export const CLIENT_SCHEMA_DIGEST = "' + hashlib.sha256(encoded.encode()).hexdigest() + '";',
             "export type ClientModels = {" + "".join(f"\n  {name}: DTO.{name};" for name in definitions) + "\n};",
             "export type ClientModelName = keyof ClientModels;",
             "function freeze(value: unknown): void { if (value !== null && typeof value === \"object\") { for (const child of Object.values(value)) freeze(child); Object.freeze(value); } }",
             "const definitions: Readonly<Record<string, JsonSchema>> = "
             + json.dumps(definitions, ensure_ascii=False, indent=2) + ";\nfreeze(definitions);\nexport const clientModelSchemas = definitions;\n"]
    return "\n\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("SDK runtime validation data is stale", file=sys.stderr)
            return 1
    else:
        TARGET.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
