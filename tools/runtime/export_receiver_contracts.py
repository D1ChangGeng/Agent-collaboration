"""Generate the implemented receiver-evidence JSON schema from its runtime types."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from pydantic import TypeAdapter

from runtime.receiver_contract import (
    NativeAdmissionCommand,
    NativeAdmissionResult,
    NativeHandoffContext,
    ReceiverSnapshot,
)

TARGET = ROOT / "docs/runtime/receiver-evidence.schema.json"
SDK_TARGET = ROOT / "sdk/receiver-evidence.ts"


def schema():
    value = TypeAdapter(ReceiverSnapshot | NativeAdmissionCommand | NativeAdmissionResult | NativeHandoffContext).json_schema()
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:acs:receiver-evidence:1", **value}


def typescript(value):
    def render(item):
        if "$ref" in item:
            return item["$ref"].rsplit("/", 1)[1]
        if "anyOf" in item:
            return " | ".join(render(child) for child in item["anyOf"])
        if "const" in item:
            return json.dumps(item["const"])
        if "enum" in item:
            return " | ".join(json.dumps(child) for child in item["enum"])
        kind = item.get("type")
        if kind == "object":
            required = item.get("required", [])
            fields = [f"  readonly {name}{'' if name in required else '?'}: {render(child)};"
                      for name, child in item.get("properties", {}).items()]
            return "{\n" + "\n".join(fields) + "\n}"
        if kind == "array":
            return "ReadonlyArray<" + render(item["items"]) + ">"
        return {"string": "string", "integer": "number", "number": "number",
                "boolean": "boolean", "null": "null"}[kind]

    lines = ["// Generated by tools/runtime/export_receiver_contracts.py. Do not edit.",
             "// Runtime validation and authorization belong to ACS; dates are RFC 3339 strings."]
    lines.extend("export type " + name + " = " + render(item) + ";"
                 for name, item in sorted(value["$defs"].items()))
    lines.append("export type ReceiverEvidence = " + render(value) + ";")
    return "\n\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = schema()
    for target, content in ((TARGET, json.dumps(value, ensure_ascii=False, indent=2) + "\n"),
                            (SDK_TARGET, typescript(value))):
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                print(f"receiver contract is stale: {target.name}", file=sys.stderr)
                return 1
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
