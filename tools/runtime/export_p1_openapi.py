"""Export the adopted P1 communication contract without changing the full API.

Tier is delivery scope, not an availability declaration. Runtime /meta and
authenticated service tests remain the authorities for enabled operations.
Requires the optional tools/runtime/requirements-contracts.txt environment.
"""
from __future__ import annotations

import argparse
import json
from copy import deepcopy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
METHODS = frozenset({"get", "put", "post", "patch", "delete", "head", "options", "trace"})
OPTIONAL_P2_FIELDS = {
    "Conversation": frozenset({"unread_count", "archived", "muted"}),
    "Message": frozenset({"attachment_refs"}),
    "Notice": frozenset({"seen"}),
}


def build_contract(full: dict, scope: dict) -> dict:
    """Validate the complete scope mapping and select its P1 operations."""
    entries = scope["operations"]
    declared = {item["operation_id"]: item for item in entries}
    if len(declared) != len(entries):
        raise ValueError("duplicate operation in API scope")
    actual = {}
    for path, methods in full["paths"].items():
        for method, operation in methods.items():
            if method not in METHODS:
                continue
            identifier = operation["operationId"]
            if identifier in actual:
                raise ValueError("duplicate OpenAPI operation: " + identifier)
            actual[identifier] = (path, method, operation)
    if actual.keys() != declared.keys():
        raise ValueError("API scope must cover every full-contract operation exactly")
    for identifier, entry in declared.items():
        path, method, operation = actual[identifier]
        if (path, method) != (entry["path"], entry["method"].lower()):
            raise ValueError("API scope route mismatch: " + identifier)
        if entry["tier"] not in {"P1_required", "P2_optional"}:
            raise ValueError("invalid communication API tier: " + identifier)
        if operation.get("x-acs-tier") != entry["tier"]:
            raise ValueError("OpenAPI tier mismatch: " + identifier)
    result = deepcopy(full)
    result["paths"] = {}
    for identifier, entry in declared.items():
        if entry["tier"] != "P1_required":
            continue
        path, method, operation = actual[identifier]
        selected = result["paths"].setdefault(path, {})
        for key, value in full["paths"][path].items():
            if key not in METHODS:
                selected[key] = deepcopy(value)
        selected[method] = deepcopy(operation)
    result["info"]["description"] = (
        "P1 communication contract selected from the adopted full API. "
        "Availability is reported by authenticated Runtime /meta. "
        "Native Host qualification and P2 features are assessed separately."
    )
    result["info"]["x-acs-scope-revision"] = scope["revision_package_version"]
    schemas = result["components"]["schemas"]
    for name, fields in OPTIONAL_P2_FIELDS.items():
        schema = schemas[name]
        if "required" in schema:
            schema["required"] = [field for field in schema["required"] if field not in fields]

    needed = set()

    def follow(value):
        if isinstance(value, dict):
            reference = value.get("$ref")
            prefix = "#/components/schemas/"
            if isinstance(reference, str) and reference.startswith(prefix):
                name = reference.removeprefix(prefix)
                if name not in schemas:
                    raise ValueError("unknown OpenAPI schema: " + name)
                if name not in needed:
                    needed.add(name)
                    follow(schemas[name])
            for child in value.values():
                follow(child)
        elif isinstance(value, list):
            for child in value:
                follow(child)

    follow(result["paths"])
    # Security schemes and other component families remain intact.
    for name, value in result["components"].items():
        if name != "schemas":
            follow(value)
    result["components"]["schemas"] = {name: value for name, value in schemas.items() if name in needed}
    return result


def render() -> str:
    full = yaml.safe_load((ROOT / "docs/client/communication-openapi.yaml").read_text(encoding="utf-8"))
    scope = json.loads((ROOT / "docs/client/communication-api-scope.json").read_text(encoding="utf-8"))
    return "# Generated by tools/runtime/export_p1_openapi.py.\n" + yaml.safe_dump(
        build_contract(full, scope), allow_unicode=True, sort_keys=False
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    path = ROOT / "docs/client/communication-p1-openapi.yaml"
    expected = render()
    if options.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("P1 OpenAPI is stale; regenerate with export_p1_openapi.py")
    else:
        path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
