"""Generate all Client 1 TypeScript DTOs from the packaged static JSON schema."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from runtime.client_contracts import ClientContracts

TARGET = ROOT / "sdk/client-contracts.ts"


def document():
    # schema() returns an owned copy and does not expose the registry's source.
    contracts = ClientContracts()
    selected = contracts.schema(contracts.model_names[0])
    return {key: value for key, value in selected.items() if key != "$ref"}


def typescript(value):
    def literal(item):
        return json.dumps(item, ensure_ascii=False)

    def render(item):
        if item is True or item == {}:
            return "unknown"
        if item is False:
            return "never"
        if "$ref" in item:
            return item["$ref"].removeprefix("#/$defs/")
        if "const" in item:
            return literal(item["const"])
        if "enum" in item:
            return " | ".join(literal(child) for child in item["enum"]) or "never"
        for keyword in ("anyOf", "oneOf"):
            if keyword in item:
                return " | ".join("(" + render(child) + ")" for child in item[keyword])
        kind = item.get("type")
        if isinstance(kind, list):
            return " | ".join(render({**item, "type": child}) for child in kind)
        if kind == "object" or "properties" in item or "required" in item:
            properties = item.get("properties", {})
            required = item.get("required", [])
            fields = [f"  readonly {literal(name)}{'' if name in required else '?'}: {render(child)};"
                      for name, child in properties.items()]
            fields.extend(f"  readonly {literal(name)}: unknown;" for name in required if name not in properties)
            result = "{\n" + "\n".join(fields) + "\n}"
            additional = item.get("additionalProperties", None)
            if additional is True or isinstance(additional, dict):
                result += " & Readonly<Record<string, " + render(additional) + ">>"
            return result
        if kind == "array":
            return "ReadonlyArray<" + render(item.get("items", {})) + ">"
        if kind is None:
            return "unknown"
        return {"string": "string", "integer": "number", "number": "number",
                "boolean": "boolean", "null": "null"}[kind]

    def conditional(base, item):
        if set(item) - {"if", "then", "else"} or "if" not in item:
            raise ValueError("unsupported client contract conditional")
        properties = item["if"].get("properties", {})
        if len(properties) != 1:
            raise ValueError("client conditional requires one discriminator")
        name, constraint = next(iter(properties.items()))
        matched = constraint.get("enum", [constraint["const"]] if "const" in constraint else None)
        declared = base["properties"][name]
        choices = declared.get("enum", [declared["const"]] if "const" in declared else None)
        if choices is None and declared.get("type") == "boolean":
            choices = [False, True]
        if choices is None and declared.get("type") == "integer" and declared.get("minimum") == 0 and matched == [0]:
            # TS cannot express nonzero integers; JSON Schema enforces the
            # positive branch's minimum at the transport boundary.
            branches = []
            for constraint, refinement in (({"const": 0}, item.get("then", {})),
                                          ({"type": "integer", "minimum": 1}, item.get("else", {}))):
                discriminator = {"type": "object", "properties": {name: constraint}, "required": [name]}
                branches.append("(" + render(discriminator) + " & " + render(refinement) + ")")
            return "(" + " | ".join(branches) + ")"
        if matched is None or choices is None:
            raise ValueError("client discriminator is not a declared finite contract")
        branches = []
        for selected, refinement in (([v for v in choices if v in matched], item.get("then", {})),
                                     ([v for v in choices if v not in matched], item.get("else", {}))):
            if selected:
                discriminator = {"type": "object", "properties": {name: {"enum": selected}}, "required": [name]}
                branches.append("(" + render(discriminator) + " & " + render(refinement) + ")")
        return "(" + " | ".join(branches) + ")"

    lines = ["// Generated by tools/runtime/export_client_contracts.py. Do not edit.",
        "// DTOs only; this file does not implement a client, transport, authorization or persistence.",
        "// RFC 3339 dates are strings; JSON Schema/Runtime enforce formats, limits and evidence semantics."]
    for name, model in value["$defs"].items():
        base = {key: child for key, child in model.items() if key != "allOf"}
        expressed = render(base)
        for item in model.get("allOf", []):
            expressed += " & " + conditional(base, item)
        lines.append("export type " + name + " = " + expressed + ";")
    return "\n\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = typescript(document())
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("client DTOs are stale", file=sys.stderr)
            return 1
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
